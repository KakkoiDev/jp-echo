// The rest of JMdict, a piece at a time.
//
// words-data.js holds the common words and every JLPT word, about a tenth of
// JMdict, and is part of the app. The other entries are in dict/: small JSON
// pieces, each holding the entries whose written forms start with characters
// that fall in that piece. A sentence fetches only the pieces for the
// characters it contains; the service worker keeps each piece it has served,
// so a word looked up once is there offline from then on.
//
// dict/manifest.json names the build ({version, count, buckets}); the pieces
// are dict/<version>/000.json to 255.json, so an address never changes.
// dict/ is generated by tools/build-words-data.mjs from the same JMdict file
// as words-data.js, so ids are JMdict's entry numbers either way. Until it has
// been generated there is no manifest, and lookups simply find nothing.

export const DICT_BUCKETS = 256;
const JAPANESE = /[぀-ヿ㐀-鿿豈-﫿]/u;

// A piece holds every entry whose written form (or kanji form) starts with a
// character whose code point falls in it.
export const bucketOf = character => character.codePointAt(0) % DICT_BUCKETS;
export const pieceName = bucket => String(bucket).padStart(3, "0") + ".json";

export function bucketsFor(text = "") {
  const buckets = new Set();
  for (const character of String(text)) if (JAPANESE.test(character)) buckets.add(bucketOf(character));
  return buckets;
}

// A verb or い-adjective can appear conjugated, so it is a candidate when its
// stem is in the text; the word matcher then decides (words.js).
const CONJUGATES = /^(v1|v5|vk|vs|vz|adj-i)/;
export const stemOf = (form, pos = []) => (form.length > 1 && pos.some(p => CONJUGATES.test(p)) ? form.slice(0, -1) : form);

// A row is [id, w, r, k|0, en, pos], the same fields as words-data.js.
export const wordFromRow = ([id, w, r, k, en, pos]) => ({id, w, r, ...(k ? {k} : {}), en, pos});

// The build's half (tools/build-words-data.mjs): words -> one list of rows per
// piece, each word under the first character of its written and kanji forms.
// A kana-only word under three characters is left out: a run of kana would
// match it by accident.
const KANA_ONLY = /^[\u3040-\u30ff]+$/u;
export function packPieces(words = []) {
  const buckets = Array.from({length: DICT_BUCKETS}, () => []);
  for (const word of words) {
    if (KANA_ONLY.test(word.w) && !word.k && [...word.w].length < 3) continue;
    const row = [word.id, word.w, word.r, word.k || 0, word.en, word.pos];
    for (const bucket of new Set([word.w, word.k].filter(Boolean).map(form => bucketOf(form)))) buckets[bucket].push(row);
  }
  return buckets;
}

export function createDictionary({fetchImpl = (...args) => fetch(...args), base = "./dict/"} = {}) {
  let manifest = null;
  const pieces = new Map();
  const ready = () => (manifest ??= fetchImpl(base + "manifest.json").then(r => (r.ok ? r.json() : null)).catch(() => null));
  const piece = bucket => {
    if (!pieces.has(bucket)) pieces.set(bucket, ready().then(m => fetchImpl(base + m.version + "/" + pieceName(bucket)))
      .then(r => (r.ok ? r.json() : []))
      .then(rows => rows.map(wordFromRow))
      // A piece that could not be fetched (offline, never seen) is asked for again next time.
      .catch(() => { pieces.delete(bucket); return []; }));
    return pieces.get(bucket);
  };
  // The looked-up words whose written or kanji form occurs in the text.
  async function wordsFor(text = "") {
    const plain = String(text);
    if (!bucketsFor(plain).size || !(await ready())) return [];
    const lists = await Promise.all([...bucketsFor(plain)].map(piece));
    const seen = new Set(), found = [];
    for (const word of lists.flat()) if (!seen.has(word.id) && [word.w, word.k].some(form => form && plain.includes(stemOf(form, word.pos)))) { seen.add(word.id); found.push(word); }
    return found;
  }
  return {wordsFor, ready};
}

// A sample for a human Japanese reviewer: two authored questions per 問題
// type (and two per comprehension tag), with key, explanation and tags.
// Scores count as readiness evidence only after this sheet is reviewed.
// Usage: node tools/n2-review-sample.mjs > docs/N2-REVIEW-SAMPLE.md
import {readFileSync} from "node:fs";
import {TAG} from "../n2-comprehension.js";

const repo = new URL("../", import.meta.url);
const read = p => JSON.parse(readFileSync(new URL(p, repo), "utf8"));
const index = read("n2-sets/index.json"), tags = read("n2-sets/tags.json").tags;
const items = [];
for (const id of Object.keys(index)) read("n2-sets/" + id + ".json").questions.forEach((q, i) => items.push({id: id + "#" + i, q, tags: tags[id + "#" + i] || []}));
// Deterministic spread: walk sets in order, take the first unpicked match.
const picked = new Map();
const take = (key, match, n = 2) => { let k = 0; for (const it of items) { if (k >= n) break; if (match(it) && !picked.has(it.id)) { picked.set(it.id, {...it, why: key}); k++; } } };
for (const it of items) { const key = it.q.skill + " 問題" + it.q.mondai; if (![...picked.values()].some(p => p.why === key)) take(key, x => x.q.skill === it.q.skill && x.q.mondai === it.q.mondai); }
for (const id of Object.keys(TAG)) take("tag " + id, x => x.tags[0] === id);
const out = ["# N2 human review sample", "",
  "Generated by `tools/n2-review-sample.mjs`. A native Japanese reviewer checks each item: the key is the only defensible answer, the Japanese is natural N2 level, the explanation agrees, and (for reading and listening) the tags name what decides it. Mark each line OK or write the fix. Echo's mock scores are practice signals until this sheet is reviewed.", "",
  "| Item | Why sampled | Reviewer |", "|---|---|---|", ...[...picked.values()].map(p => "| " + p.id + " | " + p.why + " | ☐ OK / fix: |"), ""];
for (const p of picked.values()) {
  out.push("## " + p.id + " · " + p.q.skill + " 問題" + p.q.mondai + (p.tags.length ? " · " + p.tags.map(t => TAG[t].ja).join("・") : ""), "");
  if (p.q.context) out.push("> " + p.q.context.replace(/\n/g, "\n> "), "");
  out.push(p.q.prompt, "", ...p.q.choices.map((c, i) => (i + 1) + ". " + c + (i + 1 === p.q.key ? " **(key)**" : "")), "", "Why: " + p.q.why, "");
}
console.log(out.join("\n"));

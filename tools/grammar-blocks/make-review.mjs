// Build the review data for the grammar block index: everything a reviewer
// needs in one file, with nothing to run. See docs/GRAMMAR-BLOCKS-REVIEW-HANDOFF.md.
//   node tools/grammar-blocks/make-review.mjs
import {readFileSync, writeFileSync} from "node:fs";
import {GLOSS_FIX, GRAMMAR_CONFUSABLE} from "../../n2-game-review.js";
import {BASIC_BLOCK} from "../../n2-game.js";

const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), "utf8"));
const index = read("../../n2-grammar-blocks.json"), inventory = read("../../n2-inventory.json"), deck = read("../../decks/n2-grammar.json").sentences;
const sentence = new Map(deck.map(s => [s.id, s]));
const uses = {};
for (const [key, p] of Object.entries(index.patterns)) for (const part of p.parts) if (part.block) (uses[part.block] ??= []).push(key);
const meaning = new Map(inventory.grammar.map(([key, , m]) => [key, GLOSS_FIX["g:" + key] || m]));

const blocks = Object.entries(index.blocks).map(([id, b]) => ({
  id, form: b.form, forms: b.forms, type: b.type, level: b.level, gloss: b.gloss, example: {ja: b.ja, en: b.en},
  basic: BASIC_BLOCK.levels.includes(b.level) && BASIC_BLOCK.types.includes(b.type),
  usedIn: uses[id].map(key => ({pattern: key, meaning: meaning.get(key)})),
}));
const patterns = inventory.grammar.map(([key, name], i) => {
  const p = index.patterns[key], s = sentence.get("n2-grammar-" + i);
  return {key, name, meaning: meaning.get(key), sentence: s ? {ja: s.target, en: s.source} : null,
    parts: p.parts.map(part => ({text: part.text, block: part.block || null, gloss: part.gloss || (part.block ? index.blocks[part.block].gloss : null)})),
    literal: p.literal || null, transparency: p.transparency, oneBlock: p.parts.length === 1};
});
const out = {note: "Generated by tools/grammar-blocks/make-review.mjs from n2-grammar-blocks.json. Do not edit: review it.",
  counts: {blocks: blocks.length, basicBlocks: blocks.filter(b => b.basic).length, patterns: patterns.length, oneBlockPatterns: patterns.filter(p => p.oneBlock).length},
  blocks, patterns, confusablePairs: GRAMMAR_CONFUSABLE};
writeFileSync(new URL("./review-data.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(JSON.stringify(out.counts), Math.round(JSON.stringify(out).length / 1024) + " KB");

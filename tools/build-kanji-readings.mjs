// Regenerates kanji-readings.js from KANJIDIC2. Run by hand:
//
//   npm i --no-save kanjidic2-json && node tools/build-kanji-readings.mjs
//
// Its own file because its own licence. The data is EDRDG's, CC BY-SA 4.0,
// and that obligation travels with kanji-readings.js and not with the MIT
// file beside it. Only what the app reads is kept: on'yomi, kun'yomi, up to
// four English meanings, and the school grade as currently assigned.
import {readFileSync, writeFileSync} from "node:fs";
const {JOYO} = await import("../kanji-data.js");

// By path, not require(): the package's exports map does not list its data.
const raw = JSON.parse(readFileSync(new URL("../node_modules/kanjidic2-json/KANJIS.json", import.meta.url), "utf8"));
const by = new Map((Array.isArray(raw) ? raw : Object.values(raw)[0]).map(x => [x.literal, x]));
const out = {}, missing = [];
for (const k of JOYO) {
  const e = by.get(k);
  if (!e) { missing.push(k); continue; }
  const rm = e.readingMeaning || e.reading_meaning || e;
  out[k] = {
    on: (rm.readings?.ja_on || []).slice(),
    kun: (rm.readings?.ja_kun || []).slice(),
    en: (rm.meanings?.en || []).slice(0, 4),
    grade: e.grade ?? null,
  };
}
// The generator asserts rather than warns. Every joyo kanji must be present,
// and the grade counts must be the ones the 2017 revision published; a source
// that has quietly changed shape should stop the build.
if (missing.length) throw new Error("joyo kanji missing from KANJIDIC2: " + missing.join(""));
const grades = {};
for (const v of Object.values(out)) grades[v.grade] = (grades[v.grade] || 0) + 1;
const expect = {1: 80, 2: 160, 3: 200, 4: 202, 5: 193, 6: 191, 8: 1110};
for (const [g, n] of Object.entries(expect)) if (grades[g] !== n) throw new Error(`grade ${g}: expected ${n}, got ${grades[g]}`);

writeFileSync(new URL("../kanji-readings.js", import.meta.url), `// Generated by tools/build-kanji-readings.mjs — do not edit by hand.
//
// For each joyo kanji: on'yomi, kun'yomi, up to four English meanings, and
// the school grade as currently assigned (the 2017 revision, in force from
// 2020 — the twenty prefecture kanji are grade 4 here; 8 is secondary school).
// Kun'yomi keep KANJIDIC's dot before okurigana: しか.る is 叱る.
//
// This file is derived from KANJIDIC2, © Electronic Dictionary Research and
// Development Group (EDRDG), used under Creative Commons Attribution-ShareAlike
// 4.0 — https://www.edrdg.org/edrdg/licence.html . This file is therefore
// itself CC BY-SA 4.0; that obligation is this file's, not the app's.

export const READINGS = ${JSON.stringify(out)};
`);
console.log("kanji-readings.js:", Object.keys(out).length, "kanji, grades", JSON.stringify(grades));

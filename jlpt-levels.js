// Word and grammar inventories for the JLPT levels other than N2.
//
// n2-inventory.json (N2) is part of the app. The other four levels are in
// levels/: one JSON file a level, in the same shape ({words: [text, reading,
// meaning], grammar: [key, name, meaning]}), fetched only when a level is
// asked for. The service worker keeps each file it has served (cache
// jp-echo-levels, which app updates leave alone), so a level opened once is
// there offline from then on, like the large dictionary (dictionary.js).
//
// levels/manifest.json names the build ({version, levels: {N5: {words,
// grammar}, …}}); the files are levels/<version>/n5.json … n1.json, so an
// address never changes. levels/ is generated by
// tools/build-level-inventories.mjs from words-data.js (JLPT tags) and
// grammar-data.js (bands); never hand-edit it.

// Easiest first. N2 is listed because it is a level, though its inventory is
// n2-inventory.json and never comes from levels/.
export const LEVELS = Object.freeze(["N5", "N4", "N3", "N2", "N1"]);
export const FETCHED_LEVELS = Object.freeze(LEVELS.filter(level => level !== "N2"));
export const levelFile = level => String(level).toLowerCase() + ".json";

// The build's half: one level's inventory from Echo's own catalogues.
// A word is written as the dictionary shows it (kana when it is usually
// written in kana); its meaning is the first sense. The same word and reading
// listed twice is kept once.
export function buildInventory(level, {words = [], grammar = []}) {
  const seen = new Set(), rows = [];
  for (const word of words) {
    if (word.jlpt !== level || !word.w || !word.r || !word.en?.[0]) continue;
    const key = word.w + "/" + word.r;
    if (seen.has(key)) continue;
    seen.add(key);
    rows.push([word.w, word.r, word.en[0].replace(/;\s*/g, ", ")]);
  }
  const points = grammar.filter(point => point.level === level).sort((a, b) => a.order - b.order).map(point => [point.id, point.title, point.hint || ""]);
  return {level, words: rows, grammar: points};
}

// The page's half. inventory(level) resolves to the level's inventory, or to
// null when it cannot be had (offline and never fetched, or levels/ not built):
// the caller then plays without that level. A failed fetch is tried again next time.
export function createLevels({fetchImpl = (...args) => fetch(...args), base = "./levels/"} = {}) {
  let manifest = null;
  const kept = new Map();
  const ready = () => (manifest ??= fetchImpl(base + "manifest.json").then(r => (r.ok ? r.json() : null)).catch(() => null)
    .then(m => { if (!m) manifest = null; return m; }));
  function inventory(level) {
    if (!FETCHED_LEVELS.includes(level)) return Promise.resolve(null);
    if (!kept.has(level)) kept.set(level, ready().then(m => (m ? fetchImpl(base + m.version + "/" + levelFile(level)) : null))
      .then(r => (r && r.ok ? r.json() : null))
      .then(data => (data && Array.isArray(data.words) && Array.isArray(data.grammar) ? data : null))
      .catch(() => null)
      .then(data => { if (!data) kept.delete(level); return data; }));
    return kept.get(level);
  }
  return {inventory, ready};
}
